// Writes the compiled SqueekArena ABI, init code and its CREATE2 address to src/contract/arena.json.
// Run from the repository root after `forge build --root contracts`.
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const out = JSON.parse(readFileSync("contracts/out/SqueekArena.sol/SqueekArena.json", "utf8"));
const SQK = "0x6872bfa5ccc3e9e440c6c16e5ffdabb8dba4cc76";
// Arachnid's deterministic deployment proxy, present on Sepolia.
const FACTORY = "0x4e59b44847b379578588920ca78fbf26c0b4956c";
const SALT = "0x" + Buffer.from("SQUEEK ARENA v1".padEnd(32, "\0")).toString("hex");
const initCode = out.bytecode.object + SQK.slice(2).padStart(64, "0");

const { keccak_256 } = await import("@noble/hashes/sha3.js").catch(() => import("@noble/hashes/sha3"));
const hex = (b) => Buffer.from(b).toString("hex");
const k = (h) => keccak_256(Buffer.from(h.replace(/^0x/, ""), "hex"));
const addr = "0x" + hex(k("ff" + FACTORY.slice(2) + SALT.slice(2) + hex(k(initCode)))).slice(24);

writeFileSync(
  "src/contract/arena.json",
  JSON.stringify({ address: addr, factory: FACTORY, salt: SALT, token: SQK, initCode, abi: out.abi }, null, 2) + "\n",
);
console.log("SqueekArena CREATE2 address", addr, "initCode bytes", (initCode.length - 2) / 2);
void createHash;
writeFileSync(
  "src/contract/arenaAbi.ts",
  "// Generated by contracts/script/export.mjs from the compiled SqueekArena. Do not edit.\nexport const arenaAbi = " +
    JSON.stringify(out.abi, null, 2) + " as const;\n",
);
